USE QLBanHang;
GO

CREATE OR ALTER PROCEDURE NhomSP_DS
AS
BEGIN
    SET NOCOUNT ON;
    SELECT MaNSP, TenNSP FROM NhomSP ORDER BY MaNSP;
END
GO

CREATE OR ALTER PROCEDURE NhomSP_CT
    @MaNSP VARCHAR(10)
AS
BEGIN
    SET NOCOUNT ON;
    SELECT MaNSP, TenNSP FROM NhomSP WHERE MaNSP = @MaNSP;
END
GO

CREATE OR ALTER PROCEDURE NhomSP_Them
    @MaNSP VARCHAR(10),
    @TenNSP NVARCHAR(100)
AS
BEGIN
    SET NOCOUNT ON;
    INSERT INTO NhomSP (MaNSP, TenNSP) VALUES (@MaNSP, @TenNSP);
END
GO

CREATE OR ALTER PROCEDURE NhomSP_Sua
    @MaNSP VARCHAR(10),
    @TenNSP NVARCHAR(100)
AS
BEGIN
    SET NOCOUNT ON;
    UPDATE NhomSP SET TenNSP = @TenNSP WHERE MaNSP = @MaNSP;
END
GO

CREATE OR ALTER PROCEDURE NhomSP_Xoa
    @MaNSP VARCHAR(10)
AS
BEGIN
    SET NOCOUNT ON;
    DELETE FROM NhomSP WHERE MaNSP = @MaNSP;
END
GO

CREATE OR ALTER PROCEDURE LoaiSP_DS
AS
BEGIN
    SET NOCOUNT ON;
    SELECT MaLSP, TenLSP, MaNSP FROM LoaiSP ORDER BY MaLSP;
END
GO

CREATE OR ALTER PROCEDURE LoaiSP_CT
    @MaLSP VARCHAR(10)
AS
BEGIN
    SET NOCOUNT ON;
    SELECT MaLSP, TenLSP, MaNSP FROM LoaiSP WHERE MaLSP = @MaLSP;
END
GO

CREATE OR ALTER PROCEDURE LoaiSP_Them
    @MaLSP VARCHAR(10),
    @TenLSP NVARCHAR(100),
    @MaNSP VARCHAR(10)
AS
BEGIN
    SET NOCOUNT ON;
    INSERT INTO LoaiSP (MaLSP, TenLSP, MaNSP) VALUES (@MaLSP, @TenLSP, @MaNSP);
END
GO

